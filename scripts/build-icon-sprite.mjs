#!/usr/bin/env node
/**
 * Generates web/public/icons/sprite.svg from @phosphor-icons/core.
 * Only Regular and Bold weights are included to keep the sprite lean.
 * Run: node scripts/build-icon-sprite.mjs
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PHOSPHOR = join(ROOT, 'node_modules/@phosphor-icons/core/assets')
const OUT = join(ROOT, 'web/public/icons/sprite.svg')

const ICONS = [
  'arrow-left',
  'arrow-right',
  'arrow-up-right',
  'book-open',
  'caret-right',
  'chat-circle',
  'check',
  'circle-notch',
  'eye',
  'eye-slash',
  'flame',
  'info',
  'lightning',
  'lock-simple',
  'smiley',
  'sparkle',
  'star',
  'trophy',
  'warning-circle',
  'x',
]

const WEIGHTS = ['regular', 'bold']

function extractInner(svg) {
  // Strip the outer <svg …> wrapper, keep inner path/circle/… elements
  return svg
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .trim()
}

const symbols = []

const FILENAME = {
  regular: (name) => `${name}.svg`,
  bold: (name) => `${name}-bold.svg`,
}

for (const weight of WEIGHTS) {
  for (const name of ICONS) {
    const path = join(PHOSPHOR, weight, FILENAME[weight](name))
    const raw = readFileSync(path, 'utf8')
    const inner = extractInner(raw)
    symbols.push(
      `  <symbol id="ph-${name}-${weight}" viewBox="0 0 256 256" fill="currentColor">\n    ${inner}\n  </symbol>`
    )
  }
}

mkdirSync(join(ROOT, 'web/public/icons'), { recursive: true })

writeFileSync(
  OUT,
  [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/build-icon-sprite.mjs — do not edit directly -->',
    '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">',
    ...symbols,
    '</svg>',
  ].join('\n')
)

console.log(`✓ Wrote ${symbols.length} symbols → ${OUT}`)
